import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { createHash } from 'node:crypto';
import { pnpm } from '../process.ts';
import { walk } from '../generators/files.ts';
import { affectedPackages, workspacePackages } from './graph.ts';
import { globalChecks, packageChecks, type Check } from './definitions.ts';

export function contentId(root: string): string {
  const hash = createHash('sha256');
  const visit = (directory: string, prefix = ''): void => {
    for (const relative of walk(
      directory,
      '',
      new Set([
        'node_modules',
        'target',
        '.git',
        '.state',
        '.template-cache',
        '.cloudflare',
        'dist',
        'artifacts',
        'playwright-report',
        'test-results',
        'desktop/src-tauri/icons',
        ...workspacePackages(root)
          .filter((pkg) => pkg.runtime === 'desktop')
          .flatMap((pkg) => [
            `${path.basename(pkg.directory)}/src-tauri/icons`,
            `${path.basename(pkg.directory)}/src-tauri/gen`,
            `${path.basename(pkg.directory)}/src-tauri/permissions/autogenerated`,
          ]),
      ]),
    )) {
      hash.update(`${prefix}${relative}\0`);
      hash.update(readFileSync(path.join(directory, relative)));
    }
  };
  // walk traverses only whitelisted source roots; dependency/cache trees never enter it.
  for (const entry of ['tools', 'docs', '.agents', '.github', 'packages'])
    if (existsSync(path.join(root, entry))) visit(path.join(root, entry), `${entry}/`);
  for (const filename of [
    'package.json',
    'pnpm-lock.yaml',
    'pnpm-workspace.yaml',
    'mise.toml',
    'tsconfig.json',
    'vite.config.ts',
    '.template.json',
    'AGENTS.md',
  ])
    if (existsSync(path.join(root, filename))) {
      hash.update(filename);
      hash.update(readFileSync(path.join(root, filename)));
    }
  return hash.digest('hex');
}

export async function gate(
  root: string,
  mode: 'pre-pr' | 'push' | 'full' | 'test' | 'build',
  base?: string,
): Promise<void> {
  const git = (args: string[]) =>
    spawnSync('git', args, { cwd: root, encoding: 'utf8', timeout: 10_000 });
  const head = git(['rev-parse', 'HEAD']).stdout.trim() || 'uncommitted';
  let changed: string[] | undefined;
  let selectionReason = 'Full selected configuration (unknown base or explicit full gate)';
  if ((mode === 'pre-pr' || mode === 'push') && base && base !== 'unknown') {
    const diff = git(['diff', '--no-renames', '--name-only', '-z', `${base}...HEAD`]);
    if (diff.status === 0) {
      changed = diff.stdout.split('\0').filter(Boolean);
      if (mode === 'pre-pr') {
        const unstaged = git(['diff', '--no-renames', '--name-only', '-z', 'HEAD']);
        const untracked = git(['ls-files', '--others', '--exclude-standard', '-z']);
        if (unstaged.status !== 0 || untracked.status !== 0) changed = undefined;
        else
          changed.push(
            ...unstaged.stdout.split('\0').filter(Boolean),
            ...untracked.stdout.split('\0').filter(Boolean),
          );
      }
      selectionReason = `Changes and reverse dependencies from ${base}, including current index/worktree for pre-pr`;
    }
  }
  const packages = workspacePackages(root);
  const selected = affectedPackages(packages, changed);
  const checks: Check[] = [
    ...(mode === 'build' ? [] : globalChecks),
    ...selected.flatMap((pkg) =>
      packageChecks(
        pkg,
        mode === 'build' ? 'build' : mode === 'test' || mode === 'push' ? 'test' : 'full',
      ),
    ),
  ];
  const before = contentId(root);
  const report = {
    schema: 1,
    sha: head,
    base: base ?? null,
    contentId: before,
    os: `${process.platform}/${process.arch}`,
    node: process.version,
    cpus: os.availableParallelism(),
    memoryBytes: os.totalmem(),
    selected: selected.map((pkg) => pkg.name),
    selectionReason,
    notRequired: packages
      .filter((pkg) => !selected.includes(pkg))
      .map((pkg) => ({
        package: pkg.name,
        reason: 'Outside the manifest dependency impact graph',
      })),
    checks: [] as {
      id: string;
      requirements: string[];
      command: string[];
      milliseconds: number;
      status: 'passed' | 'failed' | 'blocked';
      reason: string;
    }[],
  };
  let failure: unknown;
  for (const check of checks) {
    const start = performance.now();
    console.log(`CHECK ${check.id}: ${check.reason}`);
    try {
      await pnpm(check.command, { cwd: root, timeout: check.timeout });
      report.checks.push({
        ...check,
        milliseconds: Math.round(performance.now() - start),
        status: 'passed',
      });
    } catch (error) {
      report.checks.push({
        ...check,
        milliseconds: Math.round(performance.now() - start),
        status: 'failed',
      });
      failure = error;
      break;
    }
  }
  for (const check of checks.slice(report.checks.length))
    report.checks.push({
      ...check,
      milliseconds: 0,
      status: 'blocked',
      reason: 'An earlier required check failed',
    });
  if (contentId(root) !== before && mode !== 'build')
    failure = new Error(
      'Unexpected source diff during read-only validation; run env:setup/codegen before the gate',
    );
  mkdirSync(path.join(root, 'artifacts'), { recursive: true });
  writeFileSync(
    path.join(root, 'artifacts', `gate-${mode}-${process.platform}.json`),
    `${JSON.stringify(report, null, 2)}\n`,
  );
  console.log(
    `${report.checks.filter((check) => check.status === 'passed').length}/${checks.length} checks passed; content ${before.slice(0, 12)}`,
  );
  if (failure) throw failure;
}

if (process.argv[1]?.endsWith(`${path.sep}gate.ts`)) {
  const mode = process.argv[2] ?? 'full';
  if (!['pre-pr', 'push', 'full', 'test', 'build'].includes(mode))
    throw new Error('Expected pre-pr|push|full|test|build');
  const baseIndex = process.argv.indexOf('--base');
  await gate(
    process.cwd(),
    mode as 'pre-pr' | 'push' | 'full' | 'test' | 'build',
    baseIndex === -1 ? undefined : process.argv[baseIndex + 1],
  );
}
