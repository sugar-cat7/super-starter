import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { applyFiles, digest, walk } from '../generators/files.ts';
import { workspacePackages } from './graph.ts';

// Omit only owned outputs and local credentials, never a matching basename in
// first-party source or a legal application directory.
function fixtureFiles(root: string) {
  const ignored = new Set([
    '.git',
    '.state',
    '.template-cache',
    'node_modules',
    'artifacts',
    'generated',
    'test-results',
    'playwright-report',
    '.env',
    '.env.local',
    '.dev.vars',
    ...workspacePackages(root).flatMap((pkg) => [
      `${pkg.directory}/node_modules`,
      `${pkg.directory}/dist`,
      `${pkg.directory}/artifacts`,
      `${pkg.directory}/test-results`,
      `${pkg.directory}/playwright-report`,
      `${pkg.directory}/.env`,
      `${pkg.directory}/.env.local`,
      `${pkg.directory}/.dev.vars`,
      ...(pkg.runtime === 'worker'
        ? [
            `${pkg.directory}/.cloudflare`,
            `${pkg.directory}/.wrangler`,
            `${pkg.directory}/src/routeTree.gen.ts`,
          ]
        : []),
      ...(pkg.runtime === 'desktop'
        ? [
            `${pkg.directory}/src-tauri/target`,
            `${pkg.directory}/src-tauri/icons`,
            `${pkg.directory}/src-tauri/gen`,
            `${pkg.directory}/src-tauri/permissions/autogenerated`,
          ]
        : []),
    ]),
  ]);
  return new Map(
    walk(root, '', new Set(), ignored).map((file) => [file, readFileSync(path.join(root, file))]),
  );
}

export function copyProjectFixture(project: string, destination: string): void {
  const files = fixtureFiles(project);
  applyFiles(destination, files);
  const fingerprint = (input: Map<string, Buffer>) =>
    [...input].map(([file, contents]) => [file, digest(contents)]);
  assert.deepEqual(
    fingerprint(fixtureFiles(destination)),
    fingerprint(files),
    'Rehearsal fixture must preserve all first-party files and workspace manifests',
  );
}
