import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { builtinModules } from 'node:module';
import { parseSync } from 'oxc-parser';
import { walk } from '../generators/files.ts';
import { workspacePackages } from './graph.ts';

export function structure(root: string): string[] {
  const errors: string[] = [];
  const packages = workspacePackages(root);
  const generatedPaths = new Set([
    '.git',
    '.state',
    '.template-cache',
    'artifacts',
    'generated',
    'playwright-report',
    'test-results',
    '.env',
    '.env.local',
    '.dev.vars',
    ...packages.flatMap((pkg) => [
      `${pkg.directory}/dist`,
      `${pkg.directory}/artifacts`,
      `${pkg.directory}/.cloudflare`,
      `${pkg.directory}/.wrangler`,
      `${pkg.directory}/src/routeTree.gen.ts`,
      ...(pkg.runtime === 'desktop'
        ? [
            `${pkg.directory}/src-tauri/target`,
            `${pkg.directory}/src-tauri/icons`,
            `${pkg.directory}/src-tauri/gen`,
            `${pkg.directory}/src-tauri/permissions/autogenerated`,
          ]
        : []),
    ]),
  ]);
  for (const filename of walk(root, '', new Set(['node_modules']), generatedPaths).filter((file) =>
    /(?:\.[cm]?[jt]sx?|\.rs|\.json|\.ya?ml|\.toml|\.md|\.mjs|\.ps1|\.env(?:\..*)?)$/u.test(
      file.replace(/\.template$/u, ''),
    ),
  )) {
    const contents = readFileSync(path.join(root, filename), 'utf8');
    if (
      /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----|\b(?:ghp_|github_pat_)[A-Za-z0-9_]{20,}/u.test(
        contents,
      )
    )
      errors.push(`${filename}: secret material detected`);
  }
  const applications = packages.filter((pkg) => pkg.runtime !== 'library');
  const builtins = new Set(builtinModules.map((module) => module.replace(/^node:/u, '')));
  const imports = new Map<string, string[]>();
  const clients: string[] = [];
  const serverModule = (specifier: string): boolean =>
    specifier.startsWith('node:') ||
    builtins.has(specifier) ||
    builtins.has(specifier.split('/')[0] ?? '') ||
    specifier.startsWith('cloudflare:') ||
    specifier === 'cf' ||
    specifier.startsWith('cf/');
  for (const legacy of ['apps', 'services'])
    if (existsSync(path.join(root, legacy)))
      errors.push(`Workspace hierarchy must be packages/*: ${legacy}`);
  for (const pkg of packages) {
    const directory = path.join(root, pkg.directory, 'src');
    if (!existsSync(directory)) continue;
    for (const relative of walk(directory).filter(
      (filename) => /\.[jt]sx?$/u.test(filename) && !filename.includes('.test.'),
    )) {
      const filename = `${pkg.directory}/src/${relative}`;
      const specifiers: string[] = [];
      imports.set(filename, specifiers);
      if (
        pkg.runtime === 'worker' &&
        /^(?:client\/|routes\/|(?:main|client)\.[jt]sx?$)/u.test(relative)
      )
        clients.push(filename);
      const contents = readFileSync(path.join(root, filename), 'utf8');
      const parsed = parseSync(filename, contents);
      if (parsed.errors.length) errors.push(`${filename}: source parse failed`);
      const checkImport = (specifier: string) => {
        specifiers.push(specifier);
        const target = specifier.startsWith('.')
          ? path.resolve(root, path.dirname(filename), specifier)
          : undefined;
        const other = applications.find(
          (app) =>
            app.name !== pkg.name &&
            (specifier === app.name ||
              specifier.startsWith(`${app.name}/`) ||
              target?.startsWith(`${path.join(root, app.directory)}${path.sep}`)),
        );
        if (other)
          errors.push(`${filename}: application implementation import is forbidden: ${specifier}`);
        const native = specifier.startsWith('@tauri-apps/') || specifier.startsWith('@wdio/');
        const server = serverModule(specifier);
        if (
          (pkg.runtime === 'library' && (native || server)) ||
          (pkg.runtime === 'worker' && native) ||
          (pkg.runtime === 'desktop' && server) ||
          (relative.startsWith('client/') && server)
        )
          errors.push(`${filename}: runtime boundary violation: ${specifier}`);
      };
      const object = (value: unknown): Record<string, unknown> | undefined =>
        value !== null && typeof value === 'object'
          ? (value as Record<string, unknown>)
          : undefined;
      const visit = (value: unknown): void => {
        if (Array.isArray(value)) {
          value.forEach(visit);
          return;
        }
        const node = object(value);
        if (!node) return;
        if (
          ['ImportDeclaration', 'ExportNamedDeclaration', 'ExportAllDeclaration'].includes(
            String(node.type),
          )
        ) {
          const source = object(node.source);
          if (typeof source?.value === 'string') checkImport(source.value);
        }
        if (
          node.type === 'ImportExpression' ||
          (node.type === 'CallExpression' && object(node.callee)?.name === 'require')
        ) {
          const source = object(
            node.type === 'ImportExpression'
              ? node.source
              : Array.isArray(node.arguments)
                ? node.arguments[0]
                : undefined,
          );
          if (typeof source?.value === 'string') checkImport(source.value);
          else
            errors.push(`${filename}: dynamic module path needs an explicit, reviewable boundary`);
        }
        Object.values(node).forEach(visit);
      };
      visit(parsed.program);
    }
  }
  const resolve = (filename: string, specifier: string): string | undefined => {
    let candidate: string | undefined;
    if (specifier.startsWith('.'))
      candidate = path.relative(root, path.resolve(root, path.dirname(filename), specifier));
    else {
      const pkg = packages.find((entry) => entry.name === specifier);
      if (pkg) candidate = `${pkg.directory}/src/index`;
    }
    if (!candidate) return;
    candidate = candidate.split(path.sep).join('/');
    const stem = candidate.replace(/\.[cm]?jsx?$/u, '');
    return [candidate, `${stem}.ts`, `${stem}.tsx`, `${stem}/index.ts`, `${stem}/index.tsx`].find(
      (entry) => imports.has(entry),
    );
  };
  const visited = new Set<string>();
  const visitClient = (filename: string, chain: string[]): void => {
    if (visited.has(filename)) return;
    visited.add(filename);
    for (const specifier of imports.get(filename) ?? []) {
      if (
        serverModule(specifier) ||
        specifier.startsWith('@tauri-apps/') ||
        /(?:^|\/)server(?:\/|\.)|\.server\./u.test(specifier)
      )
        errors.push(
          `${filename}: client dependency boundary violation: ${specifier}; reached through ${chain.join(' -> ')}`,
        );
      const target = resolve(filename, specifier);
      if (target) visitClient(target, [...chain, filename]);
    }
  };
  clients.forEach((filename) => visitClient(filename, [filename]));
  return errors;
}

if (process.argv[1]?.endsWith(`${path.sep}structure.ts`)) {
  const errors = structure(process.cwd());
  if (errors.length) {
    console.error(errors.join('\n'));
    process.exitCode = 1;
  } else console.log('Workspace and runtime boundaries passed');
}
