import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { digest, walk } from './files.ts';
import type { TemplateState } from './render.ts';
import { workspacePackages } from '../quality/graph.ts';

// User projects remain editable. Canonical acceptance requires unchanged rendered
// files plus the finalized lock; it cannot relabel user changes as generation.
export function baselineDifferences(root: string): string[] {
  const state = JSON.parse(
    readFileSync(path.join(root, '.template.json'), 'utf8'),
  ) as TemplateState;
  const differences = Object.entries(state.managed)
    .filter(
      ([file, hash]) =>
        !existsSync(path.join(root, file)) || digest(readFileSync(path.join(root, file))) !== hash,
    )
    .map(([file]) => file);
  const generated = new Set(
    workspacePackages(root).flatMap((pkg) => [
      `${pkg.directory}/.cloudflare`,
      `${pkg.directory}/.wrangler`,
      `${pkg.directory}/dist`,
      `${pkg.directory}/artifacts`,
      `${pkg.directory}/test-results`,
      `${pkg.directory}/playwright-report`,
      `${pkg.directory}/src/routeTree.gen.ts`,
      ...(pkg.runtime === 'desktop'
        ? [
            `${pkg.directory}/src-tauri/icons`,
            `${pkg.directory}/src-tauri/gen`,
            `${pkg.directory}/src-tauri/permissions/autogenerated`,
            `${pkg.directory}/src-tauri/target`,
          ]
        : []),
    ]),
  );
  for (const directory of ['tools', 'docs', '.agents', '.github', 'packages'])
    if (existsSync(path.join(root, directory)))
      for (const file of walk(
        path.join(root, directory),
        directory,
        new Set(['node_modules']),
        generated,
      ))
        if (!(file in state.managed)) differences.push(file);
  if (
    !existsSync(path.join(root, 'pnpm-lock.yaml')) ||
    state.lockId !== digest(readFileSync(path.join(root, 'pnpm-lock.yaml')))
  )
    differences.push('pnpm-lock.yaml');
  return [...new Set(differences)].toSorted();
}
