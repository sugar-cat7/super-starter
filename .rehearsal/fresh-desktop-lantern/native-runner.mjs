function contentId(root) {
  const hash = createHash('sha256');
  const generated = new Set(
    workspacePackages(root).flatMap((pkg) => [
      `${pkg.directory}/dist`,
      `${pkg.directory}/artifacts`,
      `${pkg.directory}/test-results`,
      `${pkg.directory}/playwright-report`,
      ...(pkg.runtime === 'worker'
        ? [
            `${pkg.directory}/.cloudflare`,
            `${pkg.directory}/.wrangler`,
            `${pkg.directory}/src/routeTree.gen.ts`,
          ]
        : []),
      ...(pkg.runtime === 'desktop'
        ? [
            `${pkg.directory}/src-tauri/target`,
            `${pkg.directory}/src-tauri/icons`,
            `${pkg.directory}/src-tauri/gen`,
            `${pkg.directory}/src-tauri/permissions/autogenerated`,
          ]
        : []),
    ]),
  );
  for (const directory of ['tools', 'docs', '.agents', '.github', 'packages'])
    if (existsSync(path.join(root, directory)))
      for (const file of walk(
        path.join(root, directory),
        directory,
        new Set(['node_modules']),
        generated,
      )) {
        hash.update(`${file}\0`);
        hash.update(readFileSync(path.join(root, file)));
      }
  for (const filename of [
    'package.json',
    'pnpm-lock.yaml',
    'pnpm-workspace.yaml',
    'mise.toml',
    'mise.security.toml',
    'mise.o11y.toml',
    'tsconfig.json',
    'vite.config.ts',
    '.template.json',
    'AGENTS.md',
    'README.md',
    'CLAUDE.md',
    'knip.ts',
    '.gitignore',
    '.gitattributes',
    '.semgrepignore',
    'renovate.json',
    'LICENSE',
  ])
    if (existsSync(path.join(root, filename))) {
      hash.update(filename);
      hash.update(readFileSync(path.join(root, filename)));
    }
  return hash.digest('hex');
}


